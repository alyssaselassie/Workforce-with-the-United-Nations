#!/usr/bin/env python3
"""Bundle data/*.json into data/data-bundle.js.

Browsers block fetch() for pages opened straight from disk (file://). The
bundle lets the site work after a double-click; when the site is served over
http, script.js loads the JSON files directly and this bundle is ignored.

Run after editing any JSON file:  python3 tools/bundle_data.py
"""
import json
from pathlib import Path

DATA = Path(__file__).resolve().parent.parent / "data"
NAMES = ["missions", "scenarios"]


def main():
    bundle = {}
    for name in NAMES:
        with open(DATA / f"{name}.json", encoding="utf-8") as f:
            bundle[name] = json.load(f)  # also validates the JSON
    out = DATA / "data-bundle.js"
    out.write_text(
        "// Generated by tools/bundle_data.py — do not edit by hand.\n"
        "window.APP_DATA = " + json.dumps(bundle, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {out.relative_to(DATA.parent)}")


if __name__ == "__main__":
    main()
