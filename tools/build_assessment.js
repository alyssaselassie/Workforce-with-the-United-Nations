#!/usr/bin/env node
// Builds the Workplace Relief Map survey and dashboard from their single source,
// apps/shared/assessment-model.js:
//   1. copies the model into the survey app, the analytics dashboard and the results service, so
//      each can be deployed on its own;
//   2. regenerates the Qualtrics file, codebook and demonstration export for the dashboard;
//   3. regenerates the database schema (Supabase / PostgreSQL) from the same question list.
// Run: node tools/build_assessment.js     Check only (used by the tests): node tools/build_assessment.js --check
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'apps/shared/assessment-model.js');
const M = require(SOURCE);
const CHECK = process.argv.includes('--check');

const COPY_HEADER = '// GENERATED COPY. Edit apps/shared/assessment-model.js, then run: node tools/build_assessment.js\n';
const COPIES = [
  'apps/survey/assets/assessment-model.js',
  'apps/analytics/assets/assessment-model.js',
  'supabase/functions/_shared/assessment-model.js'
];

function sql() {
  const s = M.schema();
  const list = (xs) => xs.map((x) => `'${x}'`).join(', ');
  const codes = s.codes.map(String);
  return `-- ${M.TITLE}: database schema for Supabase (PostgreSQL).
-- GENERATED by tools/build_assessment.js from apps/shared/assessment-model.js. Do not edit by hand.
--
-- Security model
--   * Respondents use the public ("anon") key. They can only call submit_assessment(): they cannot
--     read, change or delete any row, and the function checks every answer before saving.
--   * Nobody can read responses through the public API. Only the assessment-release Edge Function
--     reads them, on the server, and it returns the aggregated Relief Map (shown only once there are
--     ${M.CONFIG.minGroupSize} responses), only to signed-in users listed in assessment_admins.
--   * Stored per response: a random id and the answer codes. No name, email, staff ID, department,
--     IP address, date or time.
--
-- Apply once: Supabase dashboard > SQL Editor > paste this file > Run (or: supabase db push).

-- 1. Responses ------------------------------------------------------------------------------------
create table if not exists public.assessment_responses (
  id uuid primary key default gen_random_uuid(),
  answers jsonb not null check (jsonb_typeof(answers) = 'object')
);
-- An earlier version also stored a department and a reporting quarter; neither is collected now.
alter table public.assessment_responses drop column if exists department, drop column if exists period;
comment on table public.assessment_responses is
  'Anonymous survey responses: answer codes only. Not readable through the public API.';

alter table public.assessment_responses enable row level security;
-- No policies on purpose: with row level security on and no policy, the anon and authenticated
-- roles can neither read nor write rows directly.
revoke all on table public.assessment_responses from public, anon, authenticated;

-- 2. Who may view results ---------------------------------------------------------------------------
-- Add a user after creating their account (Authentication > Users > Add user):
--   insert into public.assessment_admins (user_id) values ('<the user''s UUID>');
create table if not exists public.assessment_admins (
  user_id uuid primary key references auth.users (id) on delete cascade
);
comment on table public.assessment_admins is
  'Accounts allowed to view aggregated results in the dashboard.';
alter table public.assessment_admins enable row level security;
revoke all on table public.assessment_admins from public, anon, authenticated;

-- 3. Submitting a response --------------------------------------------------------------------------
-- The only way in for respondents. It checks that every one of the ${s.items.length} questions has a
-- valid answer code.
drop function if exists public.submit_assessment(text, jsonb);
create or replace function public.submit_assessment(p_answers jsonb)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  expected text[] := array[${list(s.items)}];
  k text;
  v jsonb;
begin
  if p_answers is null or jsonb_typeof(p_answers) <> 'object' then
    raise exception 'The answers are missing.' using errcode = '22023';
  end if;
  if (select count(*) from jsonb_object_keys(p_answers)) <> cardinality(expected) then
    raise exception 'Every question needs exactly one answer.' using errcode = '22023';
  end if;
  foreach k in array expected loop
    v := p_answers -> k;
    if v is null or jsonb_typeof(v) <> 'number' or not ((v #>> '{}') = any (array[${list(codes)}])) then
      raise exception 'Invalid answer for question %.', k using errcode = '22023';
    end if;
  end loop;
  insert into public.assessment_responses (answers) values (p_answers);
end;
$$;

revoke all on function public.submit_assessment(jsonb) from public;
grant execute on function public.submit_assessment(jsonb) to anon, authenticated;
`;
}

const outputs = {
  'apps/analytics/downloads/assessment-qualtrics.txt': M.qualtricsTxt(),
  'apps/analytics/downloads/assessment-codebook.csv': M.codebookCSV(),
  'apps/analytics/downloads/demo-qualtrics-export.csv': M.demoCSV(),
  'supabase/migrations/20261117000000_workforce_assessment.sql': sql()
};
const source = fs.readFileSync(SOURCE, 'utf8');
COPIES.forEach((p) => { outputs[p] = COPY_HEADER + source; });

let stale = 0;
Object.entries(outputs).forEach(([rel, text]) => {
  const file = path.join(ROOT, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === text) return;
  if (CHECK) { stale += 1; console.error(`out of date: ${rel}`); return; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
  console.log(`wrote ${rel}`);
});
if (CHECK) {
  if (stale) { console.error('Run: node tools/build_assessment.js'); process.exit(1); }
  console.log('All generated assessment files are up to date.');
}
